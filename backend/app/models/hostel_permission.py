"""
SQLAlchemy ORM models for Hostel Exit Permission System.
Models:
1. HostelPermission: Digital leave/exit permission requests for hostellers.
2. ActiveOuting: Hostellers currently outside campus awaiting return.
3. SecurityAlert: Security incidents (e.g. exit denied, late return, unauthorized attempt).
"""

from datetime import datetime
from typing import Optional
from sqlalchemy import (
    Integer,
    String,
    Boolean,
    DateTime,
    Text,
    ForeignKey,
    func
)
from sqlalchemy.orm import Mapped, mapped_column, relationship
from ..db.base import Base


class HostelPermission(Base):
    """Digital exit pass / permission request for a hosteller."""
    __tablename__ = "hostel_permissions"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    student_id: Mapped[str] = mapped_column(String(50), index=True, nullable=False)
    student_name: Mapped[str] = mapped_column(String(120), nullable=False)
    reason: Mapped[str] = mapped_column(Text, nullable=False)

    # Validity window
    departure_date: Mapped[str] = mapped_column(String(20), nullable=False)  # YYYY-MM-DD
    departure_time: Mapped[str] = mapped_column(String(20), nullable=False)  # HH:MM or HH:MM:SS
    valid_from: Mapped[datetime] = mapped_column(DateTime, nullable=False)

    expected_return_date: Mapped[str] = mapped_column(String(20), nullable=False)  # YYYY-MM-DD
    expected_return_time: Mapped[str] = mapped_column(String(20), nullable=False)  # HH:MM or HH:MM:SS
    valid_until: Mapped[datetime] = mapped_column(DateTime, nullable=False)

    # Status: 'Pending', 'Approved', 'Rejected', 'Used', 'Expired'
    status: Mapped[str] = mapped_column(String(20), default="Pending", nullable=False, index=True)

    approved_by: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    approved_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)
    rejection_reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # When marked as Used (on exit gate authorization)
    used_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)

    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), onupdate=func.now(), nullable=False
    )

    def __repr__(self) -> str:
        return f"<HostelPermission(id={self.id}, student_id='{self.student_id}', status='{self.status}')>"


class ActiveOuting(Base):
    """Hosteller currently outside campus under an approved exit permission."""
    __tablename__ = "active_outings"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    permission_id: Mapped[int] = mapped_column(Integer, ForeignKey("hostel_permissions.id"), nullable=False, index=True)
    student_id: Mapped[str] = mapped_column(String(50), index=True, nullable=False)
    student_name: Mapped[str] = mapped_column(String(120), nullable=False)
    hostel_name: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    hostel_block: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    room_number: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)

    actual_exit_time: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    expected_return_time: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    actual_return_time: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)

    # Status: 'Out' (Active outing), 'Returned', 'Late' (Overdue)
    status: Mapped[str] = mapped_column(String(20), default="Out", nullable=False, index=True)

    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now(), nullable=False)
    updated_at: Mapped[datetime] = mapped_column(
        DateTime, server_default=func.now(), onupdate=func.now(), nullable=False
    )

    def __repr__(self) -> str:
        return f"<ActiveOuting(id={self.id}, student_id='{self.student_id}', status='{self.status}')>"


class SecurityAlert(Base):
    """Security alert record generated by gate events (missing pass, denied exit, late return)."""
    __tablename__ = "security_alerts"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    alert_type: Mapped[str] = mapped_column(String(50), nullable=False, index=True)
    # e.g. 'HOSTEL_EXIT_DENIED', 'LATE_RETURN', 'PERMISSION_EXPIRED', 'UNKNOWN_FACE'

    severity: Mapped[str] = mapped_column(String(20), default="HIGH", nullable=False)  # 'LOW', 'MEDIUM', 'HIGH', 'CRITICAL'
    student_id: Mapped[Optional[str]] = mapped_column(String(50), nullable=True, index=True)
    student_name: Mapped[Optional[str]] = mapped_column(String(120), nullable=True)
    gate_id: Mapped[str] = mapped_column(String(20), default="exit", nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)

    is_resolved: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    resolved_by: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    resolved_at: Mapped[Optional[datetime]] = mapped_column(DateTime, nullable=True)

    created_at: Mapped[datetime] = mapped_column(DateTime, server_default=func.now(), nullable=False, index=True)

    def __repr__(self) -> str:
        return f"<SecurityAlert(id={self.id}, type='{self.alert_type}', student='{self.student_id}')>"
